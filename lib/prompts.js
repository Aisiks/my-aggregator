// ============================================================
// lib/prompts.js — инструкции для моделей
// Два режима:
//   ask   — пользователь задаёт вопрос, модели отвечают независимо;
//   check — пользователь вставляет ответ другого ИИ (обычно ChatGPT),
//           модели независимо проверяют каждое утверждение.
// Все модели отвечают строго в JSON, чтобы судья мог сравнить их по пунктам.
// ============================================================

// Темы: короткий контекст, который модели получают вместе с вопросом
const TOPICS = {
  tax: 'Тема: налоги и бухгалтерия ИП/ТОО в Казахстане. ВАЖНО: с 01.01.2026 в РК действует новый Налоговый кодекс — ставки, режимы, пороги и сроки изменились. Если твоё знание может быть устаревшим, прямо скажи это и снизь уверенность.',
  law: 'Тема: право и договоры в Казахстане. Называй конкретный закон или кодекс РК, который нужно проверить. Не выдумывай номера статей: если не уверен в номере — так и скажи.',
  study: 'Тема: поступление, ЕНТ, гранты и выбор специальности в Казахстане. Проходные баллы и количество грантов меняются каждый год — указывай год данных и говори, если не уверен.',
  business: 'Тема: решение в малом бизнесе (Казахстан/СНГ). Разделяй факты и допущения, считай деньги в тенге.',
  general: 'Тема: общий вопрос.'
};

const SHARED = `Ты — один из нескольких независимых экспертов. Другие модели отвечают на тот же вопрос отдельно, потом ваши ответы сравнят.
Правила:
- Отвечай на языке пользователя (русский, казахский или английский).
- Точность важнее уверенности. Если не знаешь или данные могли устареть — скажи это.
- Каждое важное утверждение вынеси отдельным пунктом в "claims", коротко и проверяемо.
- В "verify" перечисли, что и где человек должен проверить перед решением (официальный источник, специалист).
- Не выдумывай ссылки, номера статей и цифры.`;

function solverPrompt({ mode, topic, question, history }) {
  const context = TOPICS[topic] || TOPICS.general;
  const past = history && history.length
    ? `\nКонтекст прошлых вопросов в этой сессии:\n${history.map(h => `- ${h}`).join('\n')}\n` : '';

  if (mode === 'check') {
    return `${SHARED}
${context}
${past}
Пользователь получил этот ответ от другого ИИ и хочет понять, можно ли ему верить:
"""
${question}
"""
Проверь каждое существенное утверждение в этом тексте.
Ответь ТОЛЬКО JSON:
{"answer": "твой вывод в 2–5 предложениях, markdown",
 "claims": [{"text": "утверждение из текста", "verdict": "верно" | "неверно" | "неясно", "why": "почему, 1 предложение", "confidence": "high" | "medium" | "low"}],
 "verify": ["что проверить и где"]}`;
  }

  return `${SHARED}
${context}
${past}
Вопрос пользователя:
"""
${question}
"""
Ответь ТОЛЬКО JSON:
{"answer": "твой ответ, markdown, до 180 слов",
 "claims": [{"text": "ключевое утверждение", "confidence": "high" | "medium" | "low"}],
 "verify": ["что проверить и где"]}`;
}

function judgePrompt({ mode, question, answers }) {
  const block = answers.map(a => `### Модель ${a.id}\n${JSON.stringify(a.data)}`).join('\n\n');
  const task = mode === 'check'
    ? 'Пользователь вставил ответ другого ИИ. Модели независимо проверили его утверждения.'
    : 'Модели независимо ответили на вопрос пользователя.';
  return `Ты — судья в сервисе PRISM. Ты НЕ отвечаешь на вопрос сам, ты сравниваешь независимые ответы моделей и честно показываешь, насколько им можно верить.
${task}

Исходный текст пользователя:
"""
${question}
"""

Ответы моделей:
${block}

Как оценивать:
- consensus (0–100): насколько модели согласны по СУТИ (не по словам). 85+ — все пришли к одному выводу; 50–84 — согласны в главном, расходятся в деталях; ниже 50 — расходятся в главном.
- Если модели согласны, но все признают, что данные могли устареть, — снизь consensus и отметь это.
- Не придумывай факты, которых нет ни у одной модели.
- escalate=true, если вопрос про деньги, налоги, право или здоровье и есть расхождение или низкая уверенность.

Ответь ТОЛЬКО JSON на языке пользователя:
{"verdict": "итоговый ответ, markdown, до 120 слов: что делать и с какой уверенностью",
 "consensus": число,
 "agreed": ["в чём модели согласны", "..."],
 "disputed": [{"point": "в чём расходятся", "positions": {"A": "позиция", "B": "позиция"}}],
 "verify": ["что проверить перед решением и где — объединённый список без повторов"],
 "escalate": true | false,
 "escalate_reason": "кому показать и почему, 1 предложение, или пустая строка"}`;
}

module.exports = { TOPICS, solverPrompt, judgePrompt };
