  function genericScenario(question, lang) {
    const t = question.replace(/\s+/g, ' ').trim().slice(0, 90);
    const ru = lang !== 'en';
    const mk = (text) => ({ answer: text, claims: [], verify: [] });
    return {
      answers: {
        A: mk(ru ? `**Демо-режим.** Здесь будет независимый ответ первой модели на вопрос «${t}».` : `**Demo mode.** The first model's independent answer to "${t}" appears here.`),
        B: mk(ru ? '**Демо-режим.** Вторая модель отвечает отдельно и не видит других ответов.' : '**Demo mode.** The second model answers separately, without seeing the others.'),
        C: mk(ru ? '**Демо-режим.** Третья модель — от другой компании, чтобы ошибки не совпадали.' : '**Demo mode.** The third model comes from a different company, so mistakes don’t line up.')
      },
      verdict: { consensus: 0,
        verdict: ru ? 'Это демо: настоящие модели не подключены, поэтому уровень согласия не считается. Попробуй один из примеров — в них разобраны реальные случаи.' : 'This is a demo: real models aren’t connected, so agreement isn’t measured. Try one of the examples.',
        agreed: [], disputed: [], verify: [], escalate: false, escalate_reason: '', demoGeneric: true }
    };
  }

  // Подбираем сценарий: сначала по выбранной теме/режиму, потом по словам вопроса
  function pick(mode, topic, question) {
    if (mode === 'check') return SCENARIOS.check.match.test(question) ? SCENARIOS.check : null;
    if (topic === 'tax' && SCENARIOS.tax.match.test(question)) return SCENARIOS.tax;
    if (topic === 'study' && SCENARIOS.study.match.test(question)) return SCENARIOS.study;
    for (const k of ['tax', 'study']) if (SCENARIOS[k].match.test(question)) return SCENARIOS[k];
    return null;
  }

  async function run({ mode, topic, question, solvers, emit }) {
    const sc = pick(mode, topic, question) || genericScenario(question, detectLang(question));
    const used = solvers.slice(0, 3);
    await Promise.all(used.map(async (s, i) => {
      await sleep(700 + i * 650 + Math.random() * 500);
      const a = sc.answers[s.id] || sc.answers.A;
      emit('model', { id: s.id, vendor: s.vendor, ms: 0, ...a });
    }));
    await sleep(900);
    emit('verdict', { ...sc.verdict, answered: used.length, total: used.length });
    emit('done', {});
  }

  const api = { run, detectLang, SCENARIOS };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.PrismDemo = api;
